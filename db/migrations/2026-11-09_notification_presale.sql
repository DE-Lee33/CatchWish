-- NOTIFICATION
ALTER TABLE NOTIFICATION ADD (
    MEMBER_ID NUMBER(10) NOT NULL REFERENCES MEMBER (MEMBER_ID),
    IS_READ   CHAR(1)    DEFAULT 'N' NOT NULL CHECK (IS_READ IN ('Y', 'N'))
);

CREATE INDEX IDX_NOTIFICATION_MEMBER ON NOTIFICATION (MEMBER_ID, CREATED_AT);

-- PRESALE_CODE
CREATE TABLE PRESALE_CODE (
    CODE_ID        NUMBER(10)   PRIMARY KEY,
    PERFORMANCE_ID NUMBER(10)   NOT NULL REFERENCES PERFORMANCE (PERFORMANCE_ID),
    CODE_VALUE     VARCHAR2(50) NOT NULL,
    SEAT_LIMIT     NUMBER(10)   NOT NULL CHECK (SEAT_LIMIT > 0),
    START_AT       DATE         NOT NULL,
    END_AT         DATE         NOT NULL,
    CREATED_AT     DATE         DEFAULT SYSDATE NOT NULL,
    CHECK (END_AT > START_AT),
    CONSTRAINT UQ_PRESALE_CODE UNIQUE (PERFORMANCE_ID, CODE_VALUE)
);

-- CHECK_AUTH_CODE
ALTER TABLE CHECK_AUTH_CODE ADD FOREIGN KEY (MEMBER_ID)      REFERENCES MEMBER (MEMBER_ID);
ALTER TABLE CHECK_AUTH_CODE ADD FOREIGN KEY (PERFORMANCE_ID) REFERENCES PERFORMANCE (PERFORMANCE_ID);

-- 시퀀스
CREATE SEQUENCE SEQ_CANCELED_TICKET_SCHEDULE;
